impl V1 {
    /// Fixture mode: make sure the caller's workspace has the fixture episode.
    async fn seed(&self, scope: &ExecutionScope) -> ApiResult<()> {
        let Some(seed) = self.fixture.clone() else {
            return Ok(());
        };
        let (store, scope) = (self.store.clone(), scope.clone());
        blocking(move || {
            let (ep, events) = seed.for_scope(&scope);
            store.import_episode(&scope, ep, events).map(|_| ())
        })
        .await
    }
}

impl HasAuth for Arc<V1> {
    fn auth(&self) -> AuthMode {
        self.auth
    }
    fn access(&self) -> Option<&access::AccessVerifier> {
        self.access.as_deref()
    }
    fn execute_code(&self) -> bool {
        self.services.sandbox.is_some()
    }
}

type St = State<Arc<V1>>;

async fn blocking<T: Send + 'static>(
    f: impl FnOnce() -> ServiceResult<T> + Send + 'static,
) -> ApiResult<T> {
    tokio::task::spawn_blocking(f)
        .await
        .map_err(|e| ApiError::new(ErrorCode::Internal, format!("blocking task: {e}")))?
        .map_err(ApiError::from)
}

