fn upload_file(v: &V1, id: &str) -> ApiResult<PathBuf> {
    if id.is_empty() || !id.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_') {
        return Err(ApiError::new(
            ErrorCode::NotFound,
            format!("upload {id} not found"),
        ));
    }
    Ok(v.uploads_dir.join(format!("{id}.part")))
}

async fn initiate_upload(
    State(v): St,
    c: Caller,
    Body(req): Body<InitiateUpload>,
) -> ApiResult<Json<UploadTicket>> {
    c.scope
        .require(Capability::WorkspaceWrite)
        .map_err(|e| ApiError::from(ErrorEnvelope::from(e)))?;
    if req.byte_length > v.max_upload_bytes {
        return Err(ApiError::new(
            ErrorCode::InvalidRequest,
            format!(
                "{} bytes exceed this deployment's upload limit of {} bytes (a storage budget, not a result limit)",
                req.byte_length, v.max_upload_bytes
            ),
        ));
    }
    if !req
        .media_type
        .split_once('/')
        .is_some_and(|(a, b)| !a.is_empty() && !b.is_empty())
    {
        return Err(ApiError::new(
            ErrorCode::InvalidRequest,
            format!("{:?} is not a media type", req.media_type),
        ));
    }
    let spec = UploadSpec {
        media_type: req.media_type,
        byte_length: req.byte_length,
        sha256: req.sha256,
        contract: req.contract,
    };
    let store = v.store.clone();
    let u = blocking(move || {
        store.create_upload(
            &c.scope,
            spec,
            req.client_request_id.as_ref(),
            Duration::from_secs(24 * 3600),
        )
    })
    .await?;
    Ok(Json(UploadTicket::of(u)))
}

async fn put_upload(
    State(v): St,
    c: Caller,
    Path(p): Path<UploadPath>,
    body: axum::body::Body,
) -> ApiResult<Json<UploadTicket>> {
    use futures_util::StreamExt;
    use sha2::Digest as _;
    use tokio::io::AsyncWriteExt;

    let path = upload_file(&v, &p.id)?;
    let (store, scope, id) = (v.store.clone(), c.scope.clone(), p.id.clone());
    let u = blocking(move || store.upload(&scope, &id)).await?;
    if u.status == UploadStatus::Completed {
        return Err(ApiError::new(
            ErrorCode::Conflict,
            format!("upload {} is already completed", p.id),
        ));
    }
    if u.expires_ms < chrono::Utc::now().timestamp_millis() {
        return Err(ApiError::new(
            ErrorCode::Conflict,
            format!("upload {} expired; initiate a new one", p.id),
        ));
    }
    let io = |e: std::io::Error| ApiError::new(ErrorCode::Internal, format!("upload staging: {e}"));
    tokio::fs::create_dir_all(&v.uploads_dir)
        .await
        .map_err(io)?;
    let tmp = path.with_extension("receiving");
    let mut file = tokio::fs::File::create(&tmp).await.map_err(io)?;
    let mut hasher = sha2::Sha256::new();
    let mut len = 0u64;
    let mut stream = body.into_data_stream();
    let mut failure = None;
    while let Some(chunk) = stream.next().await {
        let chunk = match chunk {
            Ok(c) => c,
            Err(e) => {
                failure = Some(ApiError::new(
                    ErrorCode::InvalidRequest,
                    format!("upload body: {e}"),
                ));
                break;
            }
        };
        len += chunk.len() as u64;
        if len > u.spec.byte_length {
            failure = Some(ApiError::new(
                ErrorCode::InvalidRequest,
                format!("more than the declared {} bytes", u.spec.byte_length),
            ));
            break;
        }
        hasher.update(&chunk);
        if let Err(e) = file.write_all(&chunk).await {
            failure = Some(io(e));
            break;
        }
    }
    if failure.is_none() {
        if let Err(e) = file.sync_all().await {
            failure = Some(io(e));
        }
    }
    drop(file);
    let digest = format!("sha256:{}", hex::encode(hasher.finalize()));
    if failure.is_none() && (len != u.spec.byte_length || digest != u.spec.sha256.as_str()) {
        failure = Some(ApiError::new(
            ErrorCode::InvalidRequest,
            format!(
                "received {len} bytes with {digest}; declared {} bytes with {}",
                u.spec.byte_length, u.spec.sha256
            ),
        ));
    }
    if let Some(f) = failure {
        let _ = tokio::fs::remove_file(&tmp).await;
        return Err(f);
    }
    tokio::fs::rename(&tmp, &path).await.map_err(io)?;
    let (store, scope, id) = (v.store.clone(), c.scope.clone(), p.id.clone());
    let u = blocking(move || store.upload_received(&scope, &id)).await?;
    Ok(Json(UploadTicket::of(u)))
}

async fn complete_upload(
    State(v): St,
    c: Caller,
    Body(req): Body<CompleteUpload>,
) -> ApiResult<Json<ArtifactRef>> {
    let path = upload_file(&v, &req.upload_id)?;
    let (store, artifacts, origin) = (v.store.clone(), v.artifacts.clone(), v.origin);
    let artifact = blocking(move || {
        let u = store.upload(&c.scope, &req.upload_id)?;
        match u.status {
            UploadStatus::Completed => {
                return Ok(u.artifact.expect("completed upload has an artifact"))
            }
            UploadStatus::Initiated => {
                return Err(ErrorEnvelope::new(
                    ErrorCode::Conflict,
                    format!("upload {} has not received its bytes", u.upload_id),
                    RetryPolicy::AfterUserAction,
                ))
            }
            UploadStatus::Received => {}
        }
        let mut f = std::fs::File::open(&path).map_err(|e| {
            ErrorEnvelope::new(
                ErrorCode::Internal,
                format!("upload staging: {e}"),
                RetryPolicy::Reconcile,
            )
        })?;
        let draft = ignis_core::services::ArtifactDraft {
            media_type: u.spec.media_type.clone(),
            contract: u.spec.contract.clone(),
            produced_by: Default::default(),
            inputs: vec![],
            origin,
        };
        let a = artifacts.put(&c.scope, draft, &mut f)?;
        if a.sha256 != u.spec.sha256 || a.byte_length != u.spec.byte_length {
            return Err(ErrorEnvelope::new(
                ErrorCode::Internal,
                "staged upload changed after verification",
                RetryPolicy::Reconcile,
            ));
        }
        store.upload_completed(&c.scope, &u.upload_id, &a)?;
        let _ = std::fs::remove_file(&path);
        Ok(a)
    })
    .await?;
    Ok(Json(artifact))
}

/// Re-read an episode's `last_seq` and wake its streams.
pub(crate) async fn notify_episode(
    v: &Arc<V1>,
    scope: &ignis_core::contracts::ExecutionScope,
    id: &EpisodeId,
) {
    let (store, scope, id2) = (v.store.clone(), scope.clone(), id.clone());
    if let Ok(Ok(ep)) = tokio::task::spawn_blocking(move || store.episode(&scope, &id2)).await {
        v.hub.notify(id, ep.last_seq);
    }
}

fn uuid_like() -> String {
    use std::sync::atomic::{AtomicU64, Ordering};
    static N: AtomicU64 = AtomicU64::new(0);
    let t = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0);
    ignis_core::hashing::sha256_hex(
        format!(
            "{t}:{}:{}",
            std::process::id(),
            N.fetch_add(1, Ordering::Relaxed)
        )
        .as_bytes(),
    )[..24]
        .to_string()
}
