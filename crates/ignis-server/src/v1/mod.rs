async fn capabilities(State(v): St, _c: Caller) -> Json<Capabilities> {
    let s = &v.services;
    let status = |ok: bool, what: &str, lane: &str| ServiceStatus {
        available: ok,
        detail: if ok {
            format!("{what} configured")
        } else {
            format!("{what} not configured yet ({lane})")
        },
    };
    let tools = ignis_mcp::catalog(s)
        .into_iter()
        .map(|t| ToolStatus {
            name: t.descriptor.name,
            effect: t.descriptor.effect,
            available: t.unavailable.is_none(),
            reason: t.unavailable.map(str::to_string),
        })
        .collect();
    Json(Capabilities {
        agent_runtime: ServiceStatus {
            available: v.runtime_report.available,
            detail: v.runtime_report.detail.clone(),
        },
        runtime_build: v.runtime_report.manifest.clone(),
        knowledge: status(s.knowledge.is_some(), "KnowledgeService", "Raul, R3"),
        datasets: status(s.datasets.is_some(), "DatasetService", "Raul, R2"),
        models: if s.models_disabled {
            ServiceStatus {
                available: false,
                detail: ignis_mcp::MODELS_DISABLED.into(),
            }
        } else {
            status(s.models.is_some(), "ModelService", "Iancu, I2")
        },
        artifact_store: ServiceStatus {
            available: true,
            detail: match v.artifact_backend {
                crate::ops::ArtifactBackend::Local => "local content-addressed store".into(),
                crate::ops::ArtifactBackend::R2 => "Cloudflare R2 bucket (S3 API), content-addressed;                      the local directory only stages uploads and caches manifests"
                    .into(),
            },
        },
        mcp: match &v.mcp_url {
            Some(url) => ServiceStatus {
                available: true,
                detail: format!(
                    "IGNIS MCP (streamable HTTP) on {url}, loopback only, {} tools registered",
                    v.tools.registered().len()
                ),
            },
            None => ServiceStatus {
                available: false,
                detail: "not served: the agent runtime is unavailable".into(),
            },
        },
        analysis_runner: ServiceStatus {
            available: v.runner_report.available,
            detail: v.runner_report.detail.clone(),
        },
        runner_environment: v.runner_report.environment.clone(),
        tools,
    })
}

async fn create_episode(
    State(v): St,
    c: Caller,
    Body(req): Body<CreateEpisode>,
) -> ApiResult<Response> {
    if !req.model_releases.is_empty() {
        let m = models(&v)?;
        let (scope, ids) = (c.scope.clone(), req.model_releases.clone());
        blocking(move || {
            ids.iter()
                .try_for_each(|id| m.release(&scope, id).map(|_| ()))
        })
        .await?;
    }
    let pins = EpisodePins {
        corpus_snapshot: c.scope.corpus_snapshot.clone(),
        model_releases: req.model_releases,
        harness: None,
    };
    let (store, origin) = (v.store.clone(), v.origin);
    // 202 for the first request and for retries alike: the client cannot tell them apart anyway.
    let (ep, _created) = blocking(move || {
        store.create_episode(&c.scope, &req.goal, &req.client_request_id, pins, origin)
    })
    .await?;
    Ok(Accepted(ep).into_response())
}

