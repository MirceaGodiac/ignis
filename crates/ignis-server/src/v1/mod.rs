/// Wakes SSE readers after commits (outbox after commit). The database stays the authority.
#[derive(Default)]
pub struct Hub {
    episodes: Mutex<HashMap<String, watch::Sender<u64>>>,
}

impl Hub {
    pub fn notify(&self, episode: &EpisodeId, last_seq: u64) {
        let mut m = self.episodes.lock().unwrap_or_else(|p| p.into_inner());
        let tx = m
            .entry(episode.to_string())
            .or_insert_with(|| watch::channel(0).0);
        tx.send_replace(last_seq);
    }

    fn subscribe(&self, episode: &EpisodeId) -> watch::Receiver<u64> {
        let mut m = self.episodes.lock().unwrap_or_else(|p| p.into_inner());
        m.entry(episode.to_string())
            .or_insert_with(|| watch::channel(0).0)
            .subscribe()
    }
}

