async fn read_artifact(
    State(v): St,
    c: Caller,
    Path(p): Path<ArtifactPath>,
    Query(q): Query<ArtifactQuery>,
) -> ApiResult<Response> {
    let a = v.artifacts.clone();
    let id = p.id.clone();
    let scope = c.scope.clone();
    let meta = blocking(move || a.stat(&scope, &id)).await?;
    if let Some(pointer) = q.pointer {
        if q.offset.is_some() || q.len.is_some() {
            return Err(ApiError::new(
                ErrorCode::InvalidRequest,
                "pointer and offset/len are exclusive",
            ));
        }
        let a = v.artifacts.clone();
        let scope = c.scope;
        let payload = blocking(move || {
            ignis_research::artifacts::read_json_pointer(a.as_ref(), &scope, &meta, &pointer)
        })
        .await?;
        return Ok(Json(payload).into_response());
    }
    let offset = q.offset.unwrap_or(0);
    let a = v.artifacts.clone();
    let (scope, id, len) = (c.scope, p.id, q.len);
    let bytes = blocking(move || {
        let mut out = Vec::new();
        a.open(&scope, &id, offset, len)?
            .read_to_end(&mut out)
            .map_err(|e| {
                ErrorEnvelope::new(ErrorCode::Internal, e.to_string(), RetryPolicy::Never)
            })?;
        Ok(out)
    })
    .await?;
    let mut r = bytes.into_response();
    let h = r.headers_mut();
    if let Ok(v) = meta.media_type.parse() {
        h.insert(axum::http::header::CONTENT_TYPE, v);
    }
    if let Ok(v) = meta.sha256.as_str().parse() {
        h.insert("x-ignis-artifact-sha256", v);
    }
    if let Ok(v) = meta.byte_length.to_string().parse() {
        h.insert("x-ignis-artifact-length", v);
    }
    Ok(r)
}

