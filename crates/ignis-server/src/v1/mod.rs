pub fn build(state: Arc<V1>) -> Router {
    let commands = ApiRouter::new()
        .api_route(
            "/capabilities",
            get_with(capabilities, |o| {
                o.summary("What this deployment can serve")
            }),
        )
        .api_route(
            "/episodes",
            post_with(create_episode, |o| {
                o.summary("Create an episode (idempotent on client_request_id)")
            })
            .get_with(list_episodes, |o| {
                o.summary("Episodes of the caller's workspace")
            }),
        )
        .api_route(
            "/episodes/{id}",
            get_with(get_episode, |o| o.summary("An episode")),
        )
        .api_route(
            "/episodes/{id}/messages",
            post_with(post_message, |o| {
                o.summary("Add a user message (idempotent on client_request_id)")
            }),
        )
        .api_route(
            "/episodes/{id}/approvals/{approval_id}",
            post_with(resolve_approval, |o| {
                o.summary("Approve or deny an escalation the agent runtime asked for (host-validated)")
            }),
        )
        .api_route(
            "/episodes/{id}/{action}",
            post_with(episode_action, |o| {
                o.summary("Pause, resume or cancel an episode")
            }),
        )
        .api_route(
            "/artifacts/{id}",
            get_with(read_artifact, |o| {
                o.summary("Artifact bytes (offset/len) or a JSON Pointer read")
            }),
        )
        .api_route(
            "/artifacts/{id}/meta",
            get_with(artifact_meta, |o| o.summary("The ArtifactRef")),
        )
        .api_route(
            "/search",
            post_with(search, |o| o.summary("Search the pinned corpus snapshot")),
        )
        .api_route(
            "/sources/{id}/pages/{page}",
            get_with(read_page, |o| {
                o.summary("Read one page of a source version")
            }),
        )
        .api_route(
            "/models",
            get_with(list_models, |o| o.summary("Model releases")),
        )
        .api_route(
            "/models/{id}",
            get_with(get_model, |o| o.summary("A model release")),
        )
        .api_route(
            "/analyses",
            post_with(submit_analysis, |o| {
                o.summary("Strict forecast as a job (accepted + JobRef)")
            }),
        )
        .api_route("/jobs/{id}", get_with(get_job, |o| o.summary("A job")))
        .api_route(
            "/jobs/{id}/cancel",
            post_with(cancel_job, |o| o.summary("Ask a job to stop")),
        )
        .api_route(
            "/uploads/initiate",
            post_with(initiate_upload, |o| {
                o.summary("Declare an upload (type, exact length, sha256); returns where to PUT the bytes")
            }),
        )
        .api_route(
            "/uploads/complete",
            post_with(complete_upload, |o| {
                o.summary("Publish verified upload bytes as an artifact (idempotent)")
            }),
        )
        .merge(sources::routes())
        .merge(data::routes())
        .merge(metrics::routes())
        // Short commands only: research work runs as jobs, big results are artifacts.
        .layer(TimeoutLayer::with_status_code(
            axum::http::StatusCode::REQUEST_TIMEOUT,
            Duration::from_secs(30),
        ))
        .layer(RequestBodyLimitLayer::new(1 << 20));
    // Upload bytes: streamed to staging, bounded by the declared length, no request timeout.
    let uploads = ApiRouter::new().api_route(
        "/uploads/{id}/content",
        put_with(put_upload, |o| {
            o.summary("Send the raw bytes of an upload (verified against its declaration)")
        }),
    );
    // The stream has no request timeout (heartbeats keep intermediaries open).
    let streams = ApiRouter::new().api_route(
        "/episodes/{id}/events",
        get_with(episode_events, |o| {
            o.summary("Resumable SSE of ResearchEvents (Last-Event-ID or ?after=)")
        }),
    );
    let mut api = OpenApi {
        info: Info {
            title: "IGNIS research API".into(),
            version: "v1".into(),
            description: Some(
                "Generated from the Axum handlers and the C0 contracts (schemars). Errors are ErrorEnvelope.".into(),
            ),
            ..Info::default()
        },
        ..OpenApi::default()
    };
    let router = ApiRouter::new()
        .merge(commands)
        .merge(streams)
        .merge(data::streams())
        .merge(uploads)
        .with_state(state.clone())
        .finish_api(&mut api);
    let doc = Arc::new(api);
    runner::spawn(state.clone());
    if let (Some(rt), Ok(h)) = (state.runtime.clone(), tokio::runtime::Handle::try_current()) {
        // Turns a previous process left open are settled from the runtime threads.
        h.spawn_blocking(move || {
            if let Err(e) = rt.recover() {
                tracing::warn!(error = %e, "agent runtime recovery");
            }
        });
    }
    router.route(
        "/openapi.json",
        axum::routing::get(move || {
            let doc = doc.clone();
            async move { Json((*doc).clone()) }
        }),
    )
}

