/// `Last-Event-ID` header (SSE resume cursor).
struct LastEventId(Option<u64>);

impl<S: Send + Sync> FromRequestParts<S> for LastEventId {
    type Rejection = Infallible;
    async fn from_request_parts(parts: &mut Parts, _: &S) -> Result<Self, Infallible> {
        Ok(LastEventId(
            parts
                .headers
                .get("last-event-id")
                .and_then(|v| v.to_str().ok())
                .and_then(|s| s.trim().parse().ok()),
        ))
    }
}

impl aide::operation::OperationInput for LastEventId {}

/// `Idempotency-Key` header, used when the body contract has no `client_request_id`.
struct IdempotencyKey(Option<ClientRequestId>);

impl<S: Send + Sync> FromRequestParts<S> for IdempotencyKey {
    type Rejection = ApiError;
    async fn from_request_parts(parts: &mut Parts, _: &S) -> Result<Self, ApiError> {
        match parts.headers.get("idempotency-key") {
            None => Ok(IdempotencyKey(None)),
            Some(v) => v
                .to_str()
                .ok()
                .and_then(|s| ClientRequestId::new(s).ok())
                .map(|k| IdempotencyKey(Some(k)))
                .ok_or_else(|| ApiError::new(ErrorCode::InvalidRequest, "bad Idempotency-Key")),
        }
    }
}

impl aide::operation::OperationInput for IdempotencyKey {}

