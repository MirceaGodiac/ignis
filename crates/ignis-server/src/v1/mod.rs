#[derive(Debug, Clone, Copy, Serialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum UploadState {
    Initiated,
    Received,
    Completed,
}

#[derive(Debug, Serialize, JsonSchema)]
pub struct UploadTicket {
    pub upload_id: String,
    pub state: UploadState,
    /// Where to `PUT` the raw bytes, relative to the API root (`/api/v1/`).
    pub put_path: String,
    pub byte_length: u64,
    pub sha256: Digest,
    pub expires_at: Timestamp,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub artifact: Option<ArtifactRef>,
}

impl UploadTicket {
    fn of(u: UploadRecord) -> Self {
        let expires = chrono::DateTime::<chrono::Utc>::from_timestamp_millis(u.expires_ms)
            .unwrap_or_default()
            .to_rfc3339_opts(chrono::SecondsFormat::Millis, true);
        UploadTicket {
            put_path: format!("uploads/{}/content", u.upload_id),
            state: match u.status {
                UploadStatus::Initiated => UploadState::Initiated,
                UploadStatus::Received => UploadState::Received,
                UploadStatus::Completed => UploadState::Completed,
            },
            upload_id: u.upload_id,
            byte_length: u.spec.byte_length,
            sha256: u.spec.sha256,
            expires_at: Timestamp::parse(&expires).unwrap_or_else(|_| Timestamp::now()),
            artifact: u.artifact,
        }
    }
}

