//! `/api/v1`: the research runtime API (task M2).
//!
//! Episodes and their append-only event logs (`ignis_research::ResearchStore`), resumable SSE,
//! content-addressed artifacts, durable jobs, and thin projections of the lanes' services
//! (`KnowledgeService`, `ModelService`, `DatasetService`). Every request carries a host-derived
//! [`ExecutionScope`] ([`io::Caller`]); records of another workspace are not found. Every error is an
//! `ErrorEnvelope`. A service that is not configured answers `503 capability_unavailable` and is
//! listed as unavailable in `GET /capabilities`, never as a negative scientific result.
//!
//! The OpenAPI document (`GET /api/v1/openapi.json`) is generated by `aide` from these handlers and
//! the contracts' `schemars` derives (no second schema system on the contract types).
//!
//! Agent runtime (M1): when a Codex App Server passed preflight ([`agent`]), a recorded user message
//! starts a turn; pause/cancel interrupt it, resume reconciles before restarting, and approvals the
//! runtime asks for are resolved through `POST /episodes/{id}/approvals/{approval_id}`. Runtime
//! notifications reach the episode log through the state store, so they stream like any event.

