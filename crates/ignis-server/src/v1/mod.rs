async fn post_message(
    State(v): St,
    c: Caller,
    Path(p): Path<EpisodePath>,
    Body(req): Body<PostMessage>,
) -> ApiResult<Accepted<MessageAccepted>> {
    let store = v.store.clone();
    let (id, scope) = (p.id.clone(), c.scope.clone());
    let (ev, fresh) =
        blocking(move || store.post_message(&scope, &id, &req.text, &req.client_request_id))
            .await?;
    if fresh {
        v.hub.notify(&ev.episode_id, ev.seq);
    }
    // The message is recorded either way; a runtime problem shows in the log and in /capabilities.
    if let Some(rt) = v.runtime.clone() {
        let (scope, id) = (c.scope, p.id);
        if let Err(e) = blocking(move || rt.kick(&scope, &id)).await {
            tracing::warn!(error = ?e, "agent runtime did not take the message");
        }
    }
    Ok(Accepted(MessageAccepted {
        episode_id: ev.episode_id,
        event_id: ev.event_id,
        seq: ev.seq,
        duplicate: !fresh,
    }))
}

async fn episode_action(
    State(v): St,
    c: Caller,
    Path(p): Path<ActionPath>,
) -> ApiResult<Json<ResearchEpisode>> {
    let action = p.action;
    let store = v.store.clone();
    let scope = c.scope.clone();
    let ep = blocking(move || store.act(&scope, &p.id, action)).await?;
    v.hub.notify(&ep.episode_id, ep.last_seq);
    // The host's status change is recorded first; then the runtime follows it.
    if let Some(rt) = v.runtime.clone() {
        let (scope, id) = (c.scope.clone(), ep.episode_id.clone());
        let r = blocking(move || match action {
            EpisodeAction::Pause => rt.interrupt(&scope, &id, StopReason::Pause),
            EpisodeAction::Cancel => rt.interrupt(&scope, &id, StopReason::Cancel),
            EpisodeAction::Resume => rt.resume(&scope, &id),
        })
        .await;
        if let Err(e) = r {
            tracing::warn!(error = ?e, "agent runtime did not follow the episode action");
        }
        let store = v.store.clone();
        let id = ep.episode_id.clone();
        return Ok(Json(blocking(move || store.episode(&c.scope, &id)).await?));
    }
    Ok(Json(ep))
}

async fn resolve_approval(
    State(v): St,
    c: Caller,
    Path(p): Path<ApprovalPath>,
    Body(req): Body<ResolveApproval>,
) -> ApiResult<Accepted<ApprovalAccepted>> {
    let rt = v
        .runtime
        .clone()
        .ok_or_else(|| ApiError::unavailable("agent runtime"))?;
    let decision = match req.decision {
        HostDecision::Approved => ApprovalDecision::Approved,
        HostDecision::Denied => ApprovalDecision::Denied,
    };
    let (episode_id, approval_id) = (p.id.clone(), p.approval_id.clone());
    blocking(move || rt.resolve_approval(&c.scope, &p.id, &p.approval_id, decision)).await?;
    Ok(Accepted(ApprovalAccepted {
        episode_id,
        approval_id,
        decision: req.decision,
    }))
}

async fn episode_events(
    State(v): St,
    c: Caller,
    Path(p): Path<EpisodePath>,
    Query(q): Query<AfterQuery>,
    LastEventId(last): LastEventId,
) -> ApiResult<EventStream<impl futures_util::Stream<Item = Result<Event, Infallible>>>> {
    let cursor = q.after.unwrap_or(0).max(last.unwrap_or(0));
    v.seed(&c.scope).await?;
    // Validate access and the cursor before the stream starts, so errors are real HTTP statuses.
    let store = v.store.clone();
    let (scope, id) = (c.scope.clone(), p.id.clone());
    let first = blocking(move || store.replay(&scope, &id, cursor, REPLAY_BATCH)).await?;
    let first = match first {
        Replay::Gone { last_seq } => return Err(ApiError::gone(last_seq)),
        Replay::Events { events, .. } => events,
    };
    let rx = v.hub.subscribe(&p.id);
    struct S {
        v: Arc<V1>,
        scope: ignis_core::contracts::ExecutionScope,
        id: EpisodeId,
        cursor: u64,
        buf: std::collections::VecDeque<ignis_core::contracts::ResearchEvent>,
        rx: watch::Receiver<u64>,
        done: bool,
    }
    let init = S {
        v,
        scope: c.scope,
        id: p.id,
        cursor,
        buf: first.into(),
        rx,
        done: false,
    };
    let stream = futures_util::stream::unfold(init, |mut s| async move {
        loop {
            if s.done {
                return None;
            }
            if let Some(ev) = s.buf.pop_front() {
                s.cursor = ev.seq;
                let kind = serde_json::to_value(&ev.body)
                    .ok()
                    .and_then(|b| b.get("kind").and_then(|k| k.as_str()).map(str::to_string))
                    .unwrap_or_else(|| "event".into());
                let event = Event::default()
                    .id(ev.seq.to_string())
                    .event(kind)
                    .json_data(&ev)
                    .unwrap_or_else(|_| Event::default().comment("unserializable event"));
                return Some((Ok(event), s));
            }
            // Wait for a commit notification; poll anyway so a missed wake-up only delays.
            let _ = tokio::time::timeout(Duration::from_secs(5), s.rx.changed()).await;
            let (store, scope, id, after) =
                (s.v.store.clone(), s.scope.clone(), s.id.clone(), s.cursor);
            match tokio::task::spawn_blocking(move || {
                store.replay(&scope, &id, after, REPLAY_BATCH)
            })
            .await
            {
                Ok(Ok(Replay::Events { events, .. })) => s.buf.extend(events),
                // Compacted under us, the episode vanished, or the store failed: end the stream;
                // the client reconnects and gets the proper status.
                _ => s.done = true,
            }
        }
    });
    Ok(EventStream(stream))
}

